#!/usr/bin/env python3
"""Writes Resources/data/enemy_routes.json from StrongholdAssistant data/garrison_routes.json (Apache-2.0; level files of
Kengxxiao/ArknightsGameData act3autochess V3_1) and the mode names of data/garrison_spawns.json.

Per map and level: every enemy route (walk / fly) as polylines of cell centres (col, row on the board grid; one per
segment, a teleport splits a path) with the number of enemies taking it; per mode and round: which level is fought (boss rounds list one level per boss).
Usage: python3 scripts/build-enemy-routes.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REFS = next((p for p in [ROOT.parent / "卫戍协议小助手-参考项目", ROOT / "references"] if p.exists()), ROOT.parent / "卫戍协议小助手-参考项目")
SRC = REFS / "StrongholdAssistant/data"
routes = json.loads((SRC / "garrison_routes.json").read_text(encoding="utf-8"))
spawns = json.loads((SRC / "garrison_spawns.json").read_text(encoding="utf-8"))

maps = {}
for map_id, m in routes["maps"].items():
    levels = {}
    for level, v in m["levels"].items():
        out = []
        for r in v["routes"]:
            # A teleport splits a path into segments (drawn one by one, no line between them).
            segs = [[[round(p["col"], 2), round(p["row"], 2)] for p in seg] for seg in r["segments"]]
            segs = [s for s in segs if len(s) >= 2]
            if not segs:
                continue
            out.append({"motion": r["motion"], "count": r.get("count", 1), "boss": r.get("boss", False),
                        "side": r.get("side"), "segments": segs})
        levels[level] = out
    maps[map_id] = levels
doc = {
    "_notice": "Enemy routes per map / level and the level of each round. From StrongholdAssistant data/garrison_routes.json "
               "(Apache-2.0, Kengxxiao/ArknightsGameData act3autochess V3_1); generated by scripts/build-enemy-routes.py.",
    "modes": spawns["modes"],
    "battles": routes["battles"],
    "bossIds": routes["bossIds"],
    "maps": maps,
}
(ROOT / "Resources/data/enemy_routes.json").write_text(json.dumps(doc, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
print((ROOT / "Resources/data/enemy_routes.json").stat().st_size, "bytes")
