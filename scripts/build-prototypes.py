#!/usr/bin/env python3
"""Writes Resources/data/prototypes.json from StrongholdAssistant data/prototypes.json (Apache-2.0).

In 卫戍协议 an operator the player does not own is shown in the shop and on the board with a stand-in model
("prototype": Pith, Sharp, 郁金香, Stormeye, …). Each shop slot that uses one is listed with its real operator and
tier, so a "Pith" card at 3本 is 卡涅利安. Usage: python3 scripts/build-prototypes.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REFS = next((p for p in [ROOT.parent / "卫戍协议小助手-参考项目", ROOT / "references"] if p.exists()), ROOT.parent / "卫戍协议小助手-参考项目")
src = json.loads((REFS / "StrongholdAssistant/data/prototypes.json").read_text(encoding="utf-8"))
ops = json.loads((ROOT / "Resources/data/operators.json").read_text(encoding="utf-8"))
ops = ops if isinstance(ops, list) else ops["operators"]
known = {o["name"] for o in ops}
out = {}
for s in src["slots"]:
    if not s.get("prototype"):
        continue
    assert s["name"] in known, s["name"]
    out.setdefault(s["prototype"], []).append({"name": s["name"], "tier": s["tier"]})
for v in out.values():
    v.sort(key=lambda e: (e["tier"], e["name"]))
doc = {
    "_notice": "Shop slots shown with a stand-in model when the player does not own the operator. From StrongholdAssistant "
               "data/prototypes.json (Apache-2.0, act3autochess V3_1); generated by scripts/build-prototypes.py.",
    "season": src.get("season"),
    "prototypes": out,
}
(ROOT / "Resources/data/prototypes.json").write_text(json.dumps(doc, ensure_ascii=False, indent=1), encoding="utf-8")
print({k: len(v) for k, v in out.items()})
